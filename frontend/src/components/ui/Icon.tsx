export type IconName = string;

interface IconProps extends Omit<LucideProps, "ref"> {
  name: IconName;
}

export function Icon({ name, size = 16, strokeWidth = 1.75, ...rest }: IconProps) {
  const Component = REGISTRY[name] ?? Circle;
  return <Component size={size} strokeWidth={strokeWidth} aria-hidden="true" {...rest} />;
}

/** Mode icon for a segment or ground transport record. */
export function modeIcon(segmentType: string): string {
  switch (segmentType) {
    case "flight":
      return "Plane";
    case "train":
      return "TrainFront";
    case "bus":
      return "BusFront";
    case "taxi":
      return "CarTaxiFront";
    case "rental_car":
      return "CarFront";
    case "transfer":
      return "CarFront";
    case "walk":
      return "Footprints";
    case "hotel":
      return "BedDouble";
    default:
      return "Route";
  }
}
